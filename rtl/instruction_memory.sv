module instruction_memory (
    input logic [31:0] address,
    output logic [31:0] instruction
);

    logic [31:0] memory [0:63];

    initial begin

        // ========================================================
        // DAY 9 COMPLETE CPU INTEGRATION PROGRAM
        // ========================================================

        // --------------------------------------------------------
        // PC = 0
        // ADDI x1, x0, 10
        // x1 = 10
        // --------------------------------------------------------
        memory[0] = 32'h00A00093;


        // --------------------------------------------------------
        // PC = 4
        // ADDI x2, x0, 20
        // x2 = 20
        // --------------------------------------------------------
        memory[1] = 32'h01400113;


        // --------------------------------------------------------
        // PC = 8
        // ADD x3, x1, x2
        // x3 = 30
        // --------------------------------------------------------
        memory[2] = 32'h002081B3;


        // --------------------------------------------------------
        // PC = 12
        // SUB x4, x2, x1
        // x4 = 10
        // --------------------------------------------------------
        memory[3] = 32'h40110233;


        // --------------------------------------------------------
        // PC = 16
        // AND x5, x1, x2
        // x5 = 0
        // --------------------------------------------------------
        memory[4] = 32'h0020F2B3;


        // --------------------------------------------------------
        // PC = 20
        // OR x6, x1, x2
        // x6 = 30
        // --------------------------------------------------------
        memory[5] = 32'h0020E333;


        // --------------------------------------------------------
        // PC = 24
        // XOR x7, x1, x2
        // x7 = 30
        // --------------------------------------------------------
        memory[6] = 32'h0020C3B3;


        // --------------------------------------------------------
        // PC = 28
        // SW x3, 0(x0)
        // memory[0] = 30
        // --------------------------------------------------------
        memory[7] = 32'h00302023;


        // --------------------------------------------------------
        // PC = 32
        // LW x8, 0(x0)
        // x8 = 30
        // --------------------------------------------------------
        memory[8] = 32'h00002403;


        // --------------------------------------------------------
        // PC = 36
        // BEQ x3, x8, +8
        //
        // If x3 == x8:
        // PC 36 + 8 = PC 44
        //
        // PC 40 instruction is skipped.
        // --------------------------------------------------------
        memory[9] = 32'h00818463;


        // --------------------------------------------------------
        // PC = 40
        // ADDI x9, x0, 99
        // SHOULD BE SKIPPED
        // --------------------------------------------------------
        memory[10] = 32'h06300493;


        // --------------------------------------------------------
        // PC = 44
        // ADDI x9, x0, 55
        // x9 = 55
        // --------------------------------------------------------
        memory[11] = 32'h03700493;


        // --------------------------------------------------------
        // PC = 48
        // JAL x10, +8
        //
        // x10 = PC + 4 = 52
        // target = PC + 8 = 56
        //
        // PC 52 instruction is skipped.
        // --------------------------------------------------------
        memory[12] = 32'h0080056F;


        // --------------------------------------------------------
        // PC = 52
        // ADDI x11, x0, 99
        // SHOULD BE SKIPPED
        // --------------------------------------------------------
        memory[13] = 32'h06300593;


        // --------------------------------------------------------
        // PC = 56
        // ADDI x11, x0, 77
        // x11 = 77
        // --------------------------------------------------------
        memory[14] = 32'h04D00593;


        // --------------------------------------------------------
        // Remaining instructions = NOP
        // --------------------------------------------------------

        memory[15] = 32'h00000013;
        memory[16] = 32'h00000013;
        memory[17] = 32'h00000013;
        memory[18] = 32'h00000013;
        memory[19] = 32'h00000013;

    end


    always_comb begin

        instruction = memory[address[7:2]];

    end

endmodule